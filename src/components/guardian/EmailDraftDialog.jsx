import React, { useState, useEffect } from 'react';
import { Dialog, DialogContent, DialogHeader, DialogTitle, DialogDescription } from '@/components/ui/dialog';
import { Loader2, Send, CheckCircle2, Mail } from 'lucide-react';
import { base44 } from '@/api/base44Client';
import { money, dateLabel } from '@/components/guardian/format';

const ACTION_LABELS = {
  cancel: 'Cancel the service',
  negotiate: 'Negotiate a lower price',
  contact: 'Contact the company',
};

export default function EmailDraftDialog({ payment, action, batchId, onClose }) {
  const [draft, setDraft] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [sending, setSending] = useState(false);
  const [sent, setSent] = useState(false);

  useEffect(() => {
    let active = true;
    setLoading(true); setError(''); setDraft(null); setSent(false);
    base44.functions.invoke('draftVendorEmail', { batchId, paymentId: payment.payment_id, actionType: action })
      .then(({ data }) => {
        if (!active) return;
        if (data.error) setError(data.error);
        else setDraft({ to: data.to, subject: data.subject, body: data.body });
      })
      .catch(e => { if (active) setError(e.response?.data?.error || e.message || 'Could not generate email draft.'); })
      .finally(() => { if (active) setLoading(false); });
    return () => { active = false; };
  }, [payment.payment_id, action, batchId]);

  const handleSend = () => {
    setSending(true);
    setTimeout(() => { setSending(false); setSent(true); }, 800);
  };

  return (
    <Dialog open onOpenChange={v => !v && onClose()}>
      <DialogContent className="max-w-lg max-h-[85vh] overflow-y-auto">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2"><Mail size={16} />{ACTION_LABELS[action]}</DialogTitle>
          <DialogDescription>Draft email to {payment.vendor} · {money(payment.amount)} · due {dateLabel(payment.due_date)}</DialogDescription>
        </DialogHeader>

        {loading && <div className="py-12 flex flex-col items-center text-muted-foreground gap-3"><Loader2 className="animate-spin text-primary" size={24} /><p className="text-xs">Generating email draft…</p></div>}

        {error && !loading && <div className="bg-danger-soft text-destructive text-xs p-3 rounded-lg">{error}</div>}

        {sent && !loading && !error && (
          <div className="flex flex-col items-center py-8 text-center gap-3">
            <span className="p-3 rounded-full bg-success-soft text-success"><CheckCircle2 size={28} /></span>
            <p className="text-sm font-semibold">Email sent</p>
            <p className="text-xs text-muted-foreground">Your email to {draft?.to} has been sent successfully.</p>
            <button onClick={onClose} className="text-xs text-primary font-medium mt-2">Close</button>
          </div>
        )}

        {draft && !loading && !error && !sent && (
          <div className="space-y-3">
            <div>
              <label className="text-[10px] font-medium text-muted-foreground uppercase tracking-wide">To</label>
              <input value={draft.to} onChange={e => setDraft({ ...draft, to: e.target.value })} className="w-full mt-1 border rounded-lg px-3 py-2 text-xs outline-none focus:border-primary" />
            </div>
            <div>
              <label className="text-[10px] font-medium text-muted-foreground uppercase tracking-wide">Subject</label>
              <input value={draft.subject} onChange={e => setDraft({ ...draft, subject: e.target.value })} className="w-full mt-1 border rounded-lg px-3 py-2 text-xs outline-none focus:border-primary" />
            </div>
            <div>
              <label className="text-[10px] font-medium text-muted-foreground uppercase tracking-wide">Message</label>
              <textarea value={draft.body} onChange={e => setDraft({ ...draft, body: e.target.value })} rows={8} className="w-full mt-1 border rounded-lg px-3 py-2 text-xs outline-none focus:border-primary resize-none" />
            </div>
            <div className="flex items-center gap-2 pt-1">
              <button onClick={handleSend} disabled={sending} className="flex items-center gap-1.5 bg-primary text-primary-foreground rounded-lg px-4 py-2 text-xs font-semibold hover:bg-primary/90 disabled:opacity-50">
                {sending ? <Loader2 size={13} className="animate-spin" /> : <Send size={13} />}Send
              </button>
              <button onClick={onClose} className="text-xs text-muted-foreground hover:text-foreground ml-auto">Cancel</button>
            </div>
            <p className="text-[10px] text-muted-foreground pt-1">Draft generated by AI. Review and edit before sending. This is a simulation — no real email is sent.</p>
          </div>
        )}
      </DialogContent>
    </Dialog>
  );
}